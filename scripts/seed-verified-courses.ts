// ─── Build row ──────────────────────────────────────────────────────────────

function buildRow(course: VerifiedCourse) {
  const location = `${course.city}, ${course.state}`;
  const primaryTee = course.tee_boxes[0];

  return {
    name: course.name,
    location,
    par: course.par,
    slope: primaryTee.slope,
    rating: primaryTee.rating,
    yards: primaryTee.yards,
    hole_data: {
      tee_boxes: course.tee_boxes,
      access: course.access,
      architect: course.architect ?? null,
      year_opened: course.year_opened ?? null,
      grass_greens: course.grass_greens ?? null,
      grass_fairways: course.grass_fairways ?? null,
      holes: course.holes,
      country: course.country,
      data_source: course.data_source,
      data_quality: course.data_source === 'verified' ? 'complete' : 'partial',
    },
  };
}

// ─── Upsert Logic ───────────────────────────────────────────────────────────

async function upsertCourse(course: VerifiedCourse): Promise<{ success: boolean; action: string }> {
  const { data: existing } = await supabase
    .from('courses')
    .select('id, name')
    .ilike('name', course.name)
    .limit(1)
    .maybeSingle();

  const row = buildRow(course);

  if (existing) {
    const { error } = await supabase
      .from('courses')
      .update(row)
      .eq('id', existing.id);

    if (error) return { success: false, action: `UPDATE FAILED: ${error.message}` };
    return { success: true, action: 'UPDATED' };
  } else {
    const { error } = await supabase
      .from('courses')
      .insert(row);

    if (error) return { success: false, action: `INSERT FAILED: ${error.message}` };
    return { success: true, action: 'INSERTED' };
  }
}

// ─── Main ───────────────────────────────────────────────────────────────────

async function main() {
  console.log('==========================================');
  console.log('  DORMIE - Seed 250+ Verified Courses');
  console.log('==========================================\n');
  console.log(`Supabase: ${SUPABASE_URL}`);
  console.log(`Courses to seed: ${VERIFIED_COURSES.length}`);
  console.log('Columns: name, location, par, slope, rating, yards, hole_data\n');

  let succeeded = 0;
  let failed = 0;
  let verified = 0;
  let community = 0;

  for (const course of VERIFIED_COURSES) {
    const teeCount = course.tee_boxes.length;
    const primaryTee = course.tee_boxes[0];
    const label = `${course.name} (${course.city}, ${course.state})`;

    process.stdout.write(`  ${label}... `);

    const result = await upsertCourse(course);

    if (result.success) {
      console.log(`${result.action} | Par ${course.par} | ${primaryTee.rating}/${primaryTee.slope} | ${primaryTee.yards}y | ${teeCount} tees | ${course.data_source}`);
      succeeded++;
      if (course.data_source === 'verified') verified++;
      else community++;
    } else {
      console.log(`FAILED: ${result.action}`);
      failed++;
    }
  }

  console.log('\n==========================================');
  console.log(`  Succeeded:  ${succeeded}`);
  console.log(`  Failed:     ${failed}`);
  console.log(`  Verified:   ${verified}`);
  console.log(`  Community:  ${community}`);
  console.log(`  Total:      ${VERIFIED_COURSES.length}`);
  console.log('==========================================\n');

  const byState: Record<string, number> = {};
  for (const course of VERIFIED_COURSES) {
    const key = course.state || course.country;
    byState[key] = (byState[key] || 0) + 1;
  }
  console.log('Courses by state/region:');
  for (const [state, count] of Object.entries(byState).sort((a, b) => b[1] - a[1])) {
    console.log(`  ${state}: ${count}`);
  }

  if (failed > 0) {
    console.log('\nNOTE: If inserts failed with RLS policy errors, run these SQL commands:');
    console.log('  CREATE POLICY "Allow anon insert" ON courses FOR INSERT TO anon WITH CHECK (true);');
    console.log('  CREATE POLICY "Allow anon update" ON courses FOR UPDATE TO anon USING (true);\n');
  }

  process.exit(failed > 0 ? 1 : 0);
}

main();
